/** The glyph table (3x5, '#' = ink), for the UI theme's pixel font (#126). */
export const GLYPH_TABLE = GLYPHS;

export function textWidth(text) {
  return Math.max(0, String(text).length * 4 - 1);
}

/** Draw text with a 1px outline (shadow) so it reads over any terrain. */
export function drawText(ctx, text, x, y, color = '#f2e6c9', outline = '#0a0807') {
  const str = String(text).toUpperCase();
  const plot = (ox, oy, col) => {
    ctx.fillStyle = col;
    [...str].forEach((ch, i) => {
      const g = GLYPHS[ch] ?? GLYPHS[' '];
      g.forEach((row, gy) => {
        for (let gx = 0; gx < 3; gx++) if (row[gx] === '#') ctx.fillRect(x + i * 4 + gx + ox, y + gy + oy, 1, 1);
      });
    });
  };
  if (outline) for (const [ox, oy] of [[-1, 0], [1, 0], [0, -1], [0, 1], [1, 1]]) plot(ox, oy, outline);
  plot(0, 0, color);
}
